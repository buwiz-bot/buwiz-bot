//! generated/index.tsx (state.mjs `writeIndex`): a stable registry, one
//! import and one map entry per module on disk, each version of each
//! artifact, and each published widget; rewritten only when that set
//! changes. And widgets/index.tsx (`writeShelf`): the shelf template,
//! copied as is from server/src/templates/shelf.tsx.

use std::path::Path;

/// The Mini Apps tab's shelf, the very file Node copies.
pub const SHELF: &str = include_str!("../../../../../server/src/templates/shelf.tsx");

/// `R<n>.tsx` names (without ".tsx") in directory order (readdirSync's:
/// libuv sorts the names bytewise).
fn modules(dir: &Path) -> Vec<String> {
    let Ok(d) = crate::hub::pipeline::versions::read_dir_sorted(dir) else { return Vec::new() };
    d.into_iter().map(|e| e.file_name().to_string_lossy().into_owned()).filter(|f| super::load::module_number(f).is_some() && f != "index.tsx").map(|f| f[..f.len() - 4].to_owned()).collect()
}

/// `<slug>.v<n>.tsx` → n.
fn version_of(f: &str) -> Option<u64> {
    let stem = f.strip_suffix(".tsx")?;
    let (_, n) = stem.rsplit_once(".v")?;
    (!n.is_empty() && n.bytes().all(|b| b.is_ascii_digit())).then(|| n.parse().ok()).flatten()
}

/// The file's text for this set of modules, and the set's key.
pub fn index_text(gen: &Path, widgets: &Path) -> (String, String) {
    let g = modules(gen);
    let pubs = modules(widgets);
    let mut vers: Vec<(String, u64, String)> = Vec::new();
    for n in &g {
        if let Ok(d) = crate::hub::pipeline::versions::read_dir_sorted(&gen.join(n)) {
            for e in d {
                let f = e.file_name().to_string_lossy().into_owned();
                if let Some(v) = version_of(&f) {
                    vers.push((n.clone(), v, f[..f.len() - 4].to_owned()));
                }
            }
        }
    }
    let sorted = |mut xs: Vec<String>| {
        xs.sort();
        xs.join(",")
    };
    let key = format!("{}|{}|{}", sorted(g.clone()), sorted(pubs.clone()), sorted(vers.iter().map(|(n, _, f)| format!("{n}@{f}")).collect()));
    let q = crate::js::quote;
    let imports: Vec<String> = g
        .iter()
        .map(|n| format!("import {n} from \"./{n}\";"))
        .chain(vers.iter().map(|(n, v, f)| format!("import {n}v{v} from \"./{n}/{f}\";")))
        .chain(pubs.iter().map(|n| format!("import {n}w from \"../widgets/{n}\";")))
        .collect();
    let map: Vec<String> = g
        .iter()
        .map(|n| format!("  {}: {n},", q(n)))
        .chain(vers.iter().map(|(n, v, _)| format!("  {}: {n}v{v},", q(&format!("{n}@v{v}")))))
        .chain(pubs.iter().map(|n| format!("  {}: {n}w,", q(&format!("{n}w")))))
        .collect();
    let text = format!("{}\n\n// Regenerated by server/app-server.mjs — module registry only.\n\nexport const MODULES: Record<string, any> = {{\n{}\n}};\n", imports.join("\n"), map.join("\n"));
    (text, key)
}

/// Writes the index when the set of modules changed since `last`.
pub fn write_index(gen: &Path, widgets: &Path, last: &mut String) {
    let (text, key) = index_text(gen, widgets);
    if key != *last {
        *last = key;
        if let Err(e) = std::fs::write(gen.join("index.tsx"), text) {
            eprintln!("buwiz-broker: generated/index.tsx: {e}");
        }
    }
}

pub fn write_shelf(widgets: &Path) -> Result<(), String> {
    std::fs::write(widgets.join("index.tsx"), SHELF).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn store_index_names_modules_versions_and_widgets() {
        let dir = std::env::temp_dir().join(format!("rox-index-{}", super::super::uuidv7()));
        let (gen, w) = (dir.join("generated"), dir.join("widgets"));
        std::fs::create_dir_all(gen.join("R2")).unwrap();
        std::fs::create_dir_all(&w).unwrap();
        for f in ["R2.tsx", "R2/two.v1.tsx", "R2/two.v12.tsx", "notR.tsx", "R2/x.tsx"] {
            std::fs::write(gen.join(f), "x").unwrap();
        }
        std::fs::write(w.join("R2.tsx"), "x").unwrap();
        let mut last = String::new();
        write_index(&gen, &w, &mut last);
        let text = std::fs::read_to_string(gen.join("index.tsx")).unwrap();
        assert!(text.starts_with("import R2 from \"./R2\";\n"), "{text}");
        assert!(text.contains("import R2v12 from \"./R2/two.v12\";"));
        assert!(text.contains("  \"R2@v1\": R2v1,\n"));
        assert!(text.ends_with("  \"R2w\": R2w,\n};\n"));
        assert_eq!(last, "R2|R2|R2@two.v1,R2@two.v12");
        std::fs::remove_file(gen.join("index.tsx")).unwrap();
        write_index(&gen, &w, &mut last);
        assert!(!gen.join("index.tsx").exists(), "the same set: no write");
        let _ = std::fs::remove_dir_all(dir);
    }
}
